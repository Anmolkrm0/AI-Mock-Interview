"""Server-side Supabase Storage client.

Uses the Storage REST API with the server-only secret key. Endpoint shapes
match the official ``storage3`` SDK:

* ``POST /object/upload/sign/{bucket}/{path}`` -> signed upload URL + token
* ``POST /object/sign/{bucket}/{path}``        -> signed download URL
* ``POST /object/list/{bucket}``               -> object metadata (size, mimetype)
* ``POST /object/{bucket}/{path}``             -> direct upload
* ``DELETE /object/{bucket}`` with prefixes    -> delete

Paths are always generated by the backend; the browser never chooses one.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from functools import lru_cache
from typing import Protocol
from urllib.parse import parse_qs, quote, urlparse

import httpx

from app.core.config import get_settings
from app.core.errors import ConfigurationError, StorageError

logger = logging.getLogger("app.storage")


@dataclass(frozen=True)
class SignedUpload:
    path: str
    token: str
    signed_url: str


@dataclass(frozen=True)
class ObjectInfo:
    path: str
    size: int
    mime_type: str | None


class StorageClient(Protocol):
    async def create_signed_upload(self, bucket: str, path: str) -> SignedUpload: ...
    async def create_signed_url(self, bucket: str, path: str, expires_in: int) -> str: ...
    async def get_object_info(self, bucket: str, path: str) -> ObjectInfo | None: ...
    async def upload(self, bucket: str, path: str, data: bytes, content_type: str) -> None: ...
    async def delete(self, bucket: str, paths: list[str]) -> None: ...


def _quote_path(path: str) -> str:
    return "/".join(quote(part, safe="") for part in path.split("/"))


class SupabaseStorage:
    def __init__(self, base_url: str, secret_key: str, timeout: float = 30.0) -> None:
        self._base = base_url.rstrip("/") + "/storage/v1"
        self._public_base = self._base
        headers = {"apikey": secret_key}
        # Legacy service_role keys are JWTs and also go in Authorization;
        # new sb_secret_ keys are accepted via the apikey header.
        if secret_key.startswith("eyJ"):
            headers["Authorization"] = f"Bearer {secret_key}"
        self._client = httpx.AsyncClient(headers=headers, timeout=timeout)

    async def _request(self, method: str, url: str, **kwargs: object) -> httpx.Response:
        try:
            response = await self._client.request(method, url, **kwargs)  # type: ignore[arg-type]
        except httpx.HTTPError as exc:
            logger.warning("storage_transport_error type=%s", type(exc).__name__)
            raise StorageError() from exc
        if response.status_code >= 400:
            logger.warning("storage_http_error status=%s", response.status_code)
            raise StorageError(
                "File storage rejected the request.",
                code="STORAGE_REJECTED",
                retryable=response.status_code >= 500,
            )
        return response

    async def create_signed_upload(self, bucket: str, path: str) -> SignedUpload:
        url = f"{self._base}/object/upload/sign/{bucket}/{_quote_path(path)}"
        data = (await self._request("POST", url)).json()
        relative = str(data.get("url", ""))
        parsed = urlparse(self._public_base + "/" + relative.lstrip("/"))
        token = (parse_qs(parsed.query).get("token") or [""])[0]
        if not token:
            raise StorageError("Storage did not return an upload token.", code="STORAGE_NO_TOKEN")
        return SignedUpload(path=path, token=token, signed_url=parsed.geturl())

    async def create_signed_url(self, bucket: str, path: str, expires_in: int) -> str:
        url = f"{self._base}/object/sign/{bucket}/{_quote_path(path)}"
        data = (await self._request("POST", url, json={"expiresIn": expires_in})).json()
        signed = data.get("signedURL") or data.get("signedUrl")
        if not signed:
            raise StorageError("Storage did not return a signed URL.", code="STORAGE_NO_URL")
        return self._public_base + "/" + str(signed).lstrip("/")

    async def get_object_info(self, bucket: str, path: str) -> ObjectInfo | None:
        folder, _, name = path.rpartition("/")
        url = f"{self._base}/object/list/{bucket}"
        body = {"prefix": folder, "search": name, "limit": 10, "offset": 0}
        items = (await self._request("POST", url, json=body)).json()
        for item in items or []:
            if item.get("name") == name and item.get("id"):
                meta = item.get("metadata") or {}
                return ObjectInfo(
                    path=path,
                    size=int(meta.get("size") or meta.get("contentLength") or 0),
                    mime_type=meta.get("mimetype"),
                )
        return None

    async def upload(self, bucket: str, path: str, data: bytes, content_type: str) -> None:
        url = f"{self._base}/object/{bucket}/{_quote_path(path)}"
        await self._request(
            "POST",
            url,
            content=data,
            headers={"Content-Type": content_type, "x-upsert": "false"},
        )

    async def delete(self, bucket: str, paths: list[str]) -> None:
        if not paths:
            return
        await self._request("DELETE", f"{self._base}/object/{bucket}", json={"prefixes": paths})


class UnconfiguredStorage:
    """Raises a clear configuration error instead of pretending to store files."""

    def _fail(self) -> None:
        raise ConfigurationError(
            "File storage is not configured. Set SUPABASE_URL and SUPABASE_SECRET_KEY.",
            code="STORAGE_NOT_CONFIGURED",
        )

    async def create_signed_upload(self, bucket: str, path: str) -> SignedUpload:
        self._fail()
        raise AssertionError

    async def create_signed_url(self, bucket: str, path: str, expires_in: int) -> str:
        self._fail()
        raise AssertionError

    async def get_object_info(self, bucket: str, path: str) -> ObjectInfo | None:
        self._fail()
        raise AssertionError

    async def upload(self, bucket: str, path: str, data: bytes, content_type: str) -> None:
        self._fail()

    async def delete(self, bucket: str, paths: list[str]) -> None:
        self._fail()


@lru_cache
def _storage() -> StorageClient:
    settings = get_settings()
    if settings.supabase_url and settings.supabase_secret_key:
        return SupabaseStorage(settings.supabase_url, settings.supabase_secret_key)
    return UnconfiguredStorage()


def get_storage_client() -> StorageClient:
    return _storage()
